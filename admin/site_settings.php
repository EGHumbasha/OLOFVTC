    `setting_value` MEDIUMTEXT   NOT NULL DEFAULT '',
    `updated_at`    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");

function getSetting(PDO $conn, string $key, string $default = ''): string {
    static $cache = null;
    if ($cache === null) {
        $rows = $conn->query("SELECT setting_key, setting_value FROM site_settings")->fetchAll(PDO::FETCH_KEY_PAIR);
        $cache = $rows ?: [];
    }
    return isset($cache[$key]) ? $cache[$key] : $default;
}

function setSetting(PDO $conn, string $key, string $value): void {
    $conn->prepare("INSERT INTO site_settings (setting_key, setting_value) VALUES(?,?) ON DUPLICATE KEY UPDATE setting_value=?, updated_at=NOW()")
         ->execute([$key, $value, $value]);
}

function handleImgUpload(string $field, string $destDir, string $prefix, string $existing = ''): string {
    if (empty($_FILES[$field]['name']) || $_FILES[$field]['error'] !== UPLOAD_ERR_OK) return $existing;
    $allowed = ['image/jpeg','image/png','image/gif','image/webp'];
    $finfo   = new finfo(FILEINFO_MIME_TYPE);
    $mime    = $finfo->file($_FILES[$field]['tmp_name']);
    if (!in_array($mime, $allowed, true)) return $existing;
    if ($_FILES[$field]['size'] > 8*1024*1024) return $existing;
    if (!is_dir($destDir)) mkdir($destDir, 0755, true);
    $extMap  = ['image/jpeg'=>'jpg','image/png'=>'png','image/gif'=>'gif','image/webp'=>'webp'];
    $name    = $prefix . '_' . bin2hex(random_bytes(6)) . '.' . $extMap[$mime];
    $dest    = $destDir . $name;
    $opt     = optimizeAndSave($_FILES[$field]['tmp_name'], $mime, $dest, 'gallery');
    if ($opt['ok']) {
        $saved = basename($opt['dest'] ?? $dest);
        if ($existing && file_exists($destDir . basename($existing))) @unlink($destDir . basename($existing));
        return $saved;
    }
    return $existing;
}

function generateContentFile(PDO $conn): void {
    $rows = $conn->query("SELECT setting_key, setting_value FROM site_settings")->fetchAll(PDO::FETCH_KEY_PAIR);
    $php  = "<?php\n// Auto-generated by site_settings.php — last updated: " . date('Y-m-d H:i:s') . "\nreturn " . var_export($rows, true) . ";\n";
    file_put_contents(__DIR__ . '/../site_content.php', $php);
}

function patchConfig(PDO $conn): void {
    $cfgPath = __DIR__ . '/config.php';
    if (!is_writable($cfgPath)) return;
    $c = file_get_contents($cfgPath);
    $map = [
        'SCHOOL_NAME'        => getSetting($conn,'school_name',''),
        'SCHOOL_EMAIL'       => getSetting($conn,'school_email',''),
        'SCHOOL_PHONE'       => getSetting($conn,'school_phone',''),
        'SCHOOL_ADDRESS'     => getSetting($conn,'school_address',''),
        'REGISTRATION_EMAIL' => getSetting($conn,'school_reg_email',''),
        'SITE_URL'           => getSetting($conn,'site_url',''),
    ];
    foreach ($map as $const => $val) {
        if (!$val) continue;
        $val = addslashes($val);
        $c = preg_replace("/define\\('{$const}',\\s*'[^']*'\\);/", "define('{$const}', '{$val}');", $c);
    }
    file_put_contents($cfgPath, $c);
}

